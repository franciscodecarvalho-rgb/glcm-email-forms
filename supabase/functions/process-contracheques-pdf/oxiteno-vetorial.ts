function transformar(a: Matriz, b: Matriz): Matriz {
  return [
    a[0] * b[0] + a[2] * b[1], a[1] * b[0] + a[3] * b[1],
    a[0] * b[2] + a[2] * b[3], a[1] * b[2] + a[3] * b[3],
    a[0] * b[4] + a[2] * b[5] + a[4], a[1] * b[4] + a[3] * b[5] + a[5],
  ];
}

function lerForma(caminho: ArrayLike<number>, matriz: Matriz): Forma | null {
  let esquerda = Infinity;
  let direita = -Infinity;
  let base = Infinity;
  let topo = -Infinity;
  let assinatura = "";
  // PDF.js 5 empacota a operação DrawOPS seguida das coordenadas.
  const coordenadas = [2, 2, 6, 0, 4];
  for (let cursor = 0; cursor < caminho.length;) {
    const operacao = caminho[cursor++];
    const quantidade = coordenadas[operacao];
    if (quantidade == null || cursor + quantidade > caminho.length) return null;
    // Normaliza closePath e a ausência do moveTo inicial.
    if (operacao !== 0 || assinatura) assinatura += operacao === 3 ? "5" : String(operacao);
    for (const fim = cursor + quantidade; cursor < fim; cursor += 2) {
      const x = matriz[0] * caminho[cursor] + matriz[2] * caminho[cursor + 1] + matriz[4];
      const y = matriz[1] * caminho[cursor] + matriz[3] * caminho[cursor + 1] + matriz[5];
      esquerda = Math.min(esquerda, x);
      direita = Math.max(direita, x);
      base = Math.min(base, y);
      topo = Math.max(topo, y);
    }
  }
  if (direita - esquerda <= .2 || direita - esquerda > 16 || topo - base <= .3 || topo - base > 17) return null;
  return { assinatura, esquerda, direita, base, topo };
}

function coletarFormas(lista: ListaOperadores, ops: Operadores): Forma[] {
  const pilha: Matriz[] = [];
  const formas: Forma[] = [];
  let matriz = IDENTIDADE;
  for (const [indice, operacao] of lista.fnArray.entries()) {
    const args = lista.argsArray[indice];
    if (operacao === ops.save) pilha.push(matriz);
    if (operacao === ops.restore) matriz = pilha.pop() ?? IDENTIDADE;
    if (operacao === ops.transform && Array.isArray(args) && args.length === 6) matriz = transformar(matriz, args as Matriz);
    if (operacao !== ops.constructPath || !Array.isArray(args)
      || (args[0] !== ops.fill && args[0] !== ops.eoFill) || args[1]?.length !== 1) continue;
    const caminho = args[1][0];
    if (!(caminho instanceof Float32Array)) continue;
    const forma = lerForma(caminho, matriz);
    if (forma) formas.push(forma);
  }
  return formas;
}

function agruparPorBase(formas: Forma[], tolerancia: number) {
  const grupos: { base: number; formas: Forma[] }[] = [];
  for (const forma of formas.sort((a, b) => b.base - a.base)) {
    const grupo = grupos.at(-1);
    if (grupo && grupo.base - forma.base <= tolerancia) grupo.formas.push(forma);
    else grupos.push({ base: forma.base, formas: [forma] });
  }
  return grupos;
}

function assinaturaDaLinha(formas: Forma[]): string {
  return formas.sort((a, b) => a.esquerda - b.esquerda).map((forma) => forma.assinatura).join(" ");
}

function centavos(valor: string): number {
  return Number(valor.replace(/[.,]/g, ""));
}

function confirmarDivisoria(
  itens: ItemTexto[], formas: Forma[], esquerda: number, direita: number, topo: number, base: number,
) {
  const dentro = (x: number, y: number) => x > esquerda && x < direita && y < topo - 4 && y > base + 4;
  const tracos = formas.filter((forma) => forma.assinatura === "1115" && forma.direita - forma.esquerda < 1.5
    && forma.topo - forma.base > 4 && dentro(forma.esquerda, forma.base));
  const xsTracos = tracos.map((forma) => forma.esquerda).sort((a, b) => a - b);
  const centroTracos = xsTracos[Math.floor(xsTracos.length / 2)];
  if (xsTracos.filter((x) => Math.abs(x - centroTracos) < 1).length >= 2) return centroTracos;
  const divisorias = itens.filter((item) => item.str.trim() === "|" && dentro(item.x, item.y));
  const xs = divisorias.map((item) => item.x).sort((a, b) => a - b);
  const centro = xs[Math.floor(xs.length / 2)];
  return xs.filter((x) => Math.abs(x - centro) < 1).length >= 3 ? centro : null;
}

function descreverLinha(itens: ItemTexto[], formas: Forma[], codigo: string, y: number, fimDescricao: number) {
  const conhecida = DESCRICOES[codigo];
  if (conhecida && assinaturaDaLinha(formas.filter((forma) => forma.esquerda >= 56 && forma.direita < 299
    && forma.base >= y - 2.5 && forma.base <= y + 4)) === conhecida[0]) return conhecida[1];
  return itens.filter((item) => item.x >= 36 && item.x < fimDescricao - 2
    && Math.abs(item.y - y) <= 4 && item.str.trim() !== "|")
    .sort((a, b) => a.x - b.x)
    .map((item) => item.x < FIM_CODIGO ? item.str.trim().replace(/^[^\s\d]*\d{4}\s*/, "") : item.str.trim())
    .join(" ").replace(/\s+/g, " ").trim();
}

export function lerOxitenoVetorial(
  lista: ListaOperadores, ops: Operadores, texto: ItemTexto[], largura: number,
): LeituraVetorialOxiteno | null {
  if (Math.abs(largura - LARGURA_ADP) > 1) return null;
  const formas = coletarFormas(lista, ops);
  // A variante predominantemente textual ou digitalizada segue a leitura normal.
  if (formas.filter((forma) => /^\d$/.test(SIMBOLOS[forma.assinatura] ?? "")).length < 100) return null;

  const pendencia = (motivo: string): never => {
    throw new Error("Oxiteno: " + motivo);
  };
  const header = texto.find((item) => item.str.trim() === "CONTA" && item.x < 200);
  const rodape = texto.find((item) => item.str.replace(/\s/g, "") === "TOTAIS");
  if (!header || !rodape) return pendencia("cabeçalho da tabela ou quadro de totais ilegível.");
  const divisoriaConta = confirmarDivisoria(texto, formas, 295, 308, header.y, rodape.y);
  const divisoriaQtde = confirmarDivisoria(texto, formas, 348, 358, header.y, rodape.y);
  const divisoriaDescontos = confirmarDivisoria(texto, formas, 451, 465, header.y, rodape.y);
  if (divisoriaConta == null || divisoriaQtde == null || divisoriaDescontos == null) {
    return pendencia("divisórias da tabela ilegíveis.");
  }

  const lerCaracteres = (grupo: Forma[]) => grupo.sort((a, b) => a.esquerda - b.esquerda)
    .map((forma) => SIMBOLOS[forma.assinatura] ?? "?").join("");
  const lerFaixa = (y: number, inicio: number, fim: number) => lerCaracteres(formas.filter((forma) =>
    forma.esquerda >= inicio && forma.direita <= fim && forma.direita - forma.esquerda <= 15
    && forma.base >= y - 2.25 && forma.base <= y + 1.45));

  const marcador = agruparPorBase(formas.filter((forma) => forma.esquerda >= 139 && forma.direita < 199
    && forma.base > rodape.y + 7 && forma.base < header.y - 6), 1.1)
    .filter((grupo) => assinaturaDaLinha(grupo.formas) === BASE_OUTROS);
  if (marcador.length !== 1) return pendencia("marcador BASE/OUTROS ilegível.");

  const linhasCodigo = agruparPorBase(formas.filter((forma) => forma.esquerda >= INICIO_CODIGO
    && forma.direita <= FIM_CODIGO && forma.base < header.y - 6 && forma.base > rodape.y + 7), 1.1);

  const itens = linhasCodigo.map(({ base, formas: formasCodigo }) => {
    const codigo = lerCaracteres(formasCodigo);
    if (!/^\d{4}$/.test(codigo)) return pendencia("código de rubrica ilegível na tabela.");
    const vencimento = lerFaixa(base, divisoriaQtde + 2.5, divisoriaDescontos - .8);
    const desconto = lerFaixa(base, divisoriaDescontos + 2.5, FIM_VALORES);
    if ((vencimento && desconto) || !MOEDA.test(vencimento || desconto)) {
      return pendencia("valor da rubrica " + codigo + " sem posição ou leitura inequívoca.");
    }
    const descricao = descreverLinha(texto, formas, codigo, base, divisoriaConta);
    if (!/\p{L}/u.test(descricao)) return pendencia("descrição da rubrica " + codigo + " ilegível.");
    const quantidade = lerFaixa(base, divisoriaConta + 2, divisoriaQtde - .8);
    if (quantidade && !MOEDA.test(quantidade)) return pendencia("quantidade da rubrica " + codigo + " ilegível.");
    const tipo = base < marcador[0].base ? "informativo" as const
      : vencimento ? "provento" as const : "desconto" as const;
    return {
      codigo, descricao, tipo,
      referencia: quantidade ? centavos(quantidade) / 100 : null,
      valor: centavos(vencimento || desconto) / 100,
    };
  });

  const totais = agruparPorBase(formas.filter((forma) => forma.base > rodape.y - 22
    && forma.base < rodape.y + 4 && forma.esquerda >= 165 && SIMBOLOS[forma.assinatura]), 1.15)
    .map(({ base }) => FAIXAS_RODAPE.map(([inicio, fim]) => lerFaixa(base, inicio, fim)))
    .filter((valores) => valores.every((valor) => MOEDA.test(valor)));
  if (!totais.length || !itens.length) return pendencia("totais impressos ou rubricas incompletos.");
  const somar = (tipo: "provento" | "desconto") => itens.filter((item) => item.tipo === tipo)
    .reduce((total, item) => total + Math.round(item.valor * 100), 0);
  const somaProventos = somar("provento");
  const somaDescontos = somar("desconto");
  const conciliados = new Set(totais.map((valores) => valores.map(centavos))
    .filter(([proventos, descontos, liquido]) => Math.abs(somaProventos - proventos) <= 5
      && Math.abs(somaDescontos - descontos) <= 5 && Math.abs(proventos - descontos - liquido) <= 5)
    .map((valores) => valores.join(",")));
  if (conciliados.size !== 1) return pendencia("divergência entre rubricas visíveis e totais impressos.");
  const [proventos, descontos, liquido] = [...conciliados][0].split(",").map(Number);
  return { itens, total_proventos: proventos / 100, total_descontos: descontos / 100, liquido: liquido / 100 };
}
